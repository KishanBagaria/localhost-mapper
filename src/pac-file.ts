import type { UpstreamPAC } from './types.js'

/**
 * PAC has no import mechanism, so chaining means inlining the previous PAC and
 * calling into it.
 *
 * The upstream source is wrapped in an IIFE, which matters: a PAC file declares
 * `function FindProxyForURL`, and at function scope that declaration is local to
 * the wrapper instead of overwriting ours. Whatever it defines is captured and
 * returned, and our own function is assigned to the global afterwards so it wins
 * even if the upstream assigned to the global implicitly.
 *
 * Anything that goes wrong at runtime — the upstream throwing, or defining
 * nothing we recognise — degrades to `DIRECT`, which is how localhost-mapper
 * behaves without chaining anyway.
 */
export function buildPACFile(lines: string[], upstream?: UpstreamPAC | null): string {
  if (!lines.length) return ''
  const rules = lines.join('\n')

  if (!upstream) {
    return `function FindProxyForURL(url, host) {
${rules}
return 'DIRECT'
}
`
  }

  // Defensive: a newline here would break out of the comment.
  const source = upstream.url.replace(/[\r\n]+/g, ' ')

  return `// Generated by localhost-mapper.
// URLs matching none of the rules below fall through to the proxy auto-config
// that was already set on this machine: ${source}
var __lhUpstream = (function () {
try {
${upstream.source}
if (typeof FindProxyForURL === 'function') return FindProxyForURL
if (typeof FindProxyForURLEx === 'function') return FindProxyForURLEx
} catch (e) {}
return null
})()
function __lhFindProxyForURL(url, host) {
${rules}
if (__lhUpstream) {
try { return __lhUpstream(url, host) } catch (e) {}
}
return 'DIRECT'
}
var FindProxyForURL = __lhFindProxyForURL
`
}

export default buildPACFile
